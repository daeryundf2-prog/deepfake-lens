"""End-to-end smoke/regression harness over fixtures/benchmark/.

This is NOT a calibrated accuracy benchmark. The fixtures are synthetic
images generated by scripts/make_benchmark_fixtures.py (committed bytes,
seeded and deterministic). The suite pins pipeline behavior only:

  * every fixture completes analysis without a "failed" status,
  * the PNG carrying an A1111-style tEXt `parameters` chunk must surface
    the metadata heuristic and land in the HIGH band,
  * unmarked synthetic/camera-like stand-ins must score lower,
  * committed fixtures regenerate byte-for-byte (determinism),
  * a per-file JSON report is emitted for trend inspection — its scores
    are smoke output, not detection-quality metrics (see
    experiments/AIDE_EVALUATION.md for measured numbers).
"""

from __future__ import annotations

import importlib.util
import json
import os
import tempfile
import unittest
from pathlib import Path

from deepfake_lens.core import RiskBand, SourceConfidence, scan_directory

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURE_DIR = REPO_ROOT / "fixtures" / "benchmark"
GENERATOR = REPO_ROOT / "scripts" / "make_benchmark_fixtures.py"
MARKER_NAME = "a1111-metadata-marker.png"
EXPECTED_IMAGES = {"real-like-texture.png", "ai-like-gradient.png", MARKER_NAME}
# README.md is scanned too (text path) — same convention as
# fixtures/deepfake-lens-sample/README.md in the CLI smoke test.
EXPECTED_FILES = EXPECTED_IMAGES | {"README.md"}


def _load_generator():
    spec = importlib.util.spec_from_file_location("make_benchmark_fixtures", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _write_report(summary, items, out_path: Path) -> dict:
    report = {
        "note": "smoke/regression output from fixtures/benchmark — NOT calibrated accuracy",
        "fixture_dir": str(FIXTURE_DIR.relative_to(REPO_ROOT)),
        "summary": summary.to_json(),
        "files": [
            {
                "name": item.name,
                "status": item.status,
                "score": item.result.score if item.result else None,
                "band": item.result.band.value if item.result else None,
                "source_label": item.result.source_guess.label if item.result else None,
                "signal_titles": [signal.title for signal in item.result.signals] if item.result else [],
            }
            for item in items
        ],
    }
    out_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return report


class BenchmarkFixturesTest(unittest.TestCase):
    def test_fixtures_regenerate_deterministically(self) -> None:
        """Committed bytes must match a fresh seeded generation."""
        generator = _load_generator()
        regenerated = generator.build_fixtures()
        self.assertEqual(set(regenerated), EXPECTED_IMAGES)
        for name, expected_bytes in regenerated.items():
            committed = FIXTURE_DIR / name
            self.assertTrue(
                committed.is_file(),
                f"{name} missing — run `python scripts/make_benchmark_fixtures.py`",
            )
            self.assertEqual(committed.read_bytes(), expected_bytes, f"{name} drifted from the generator output")


class BenchmarkE2ETest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        if not FIXTURE_DIR.is_dir():
            raise unittest.SkipTest(f"{FIXTURE_DIR} missing — run `python scripts/make_benchmark_fixtures.py`")
        cls.summary, cls.items = scan_directory(FIXTURE_DIR)
        cls.by_name = {item.name: item for item in cls.items}

    def test_pipeline_completes_with_no_failures(self) -> None:
        self.assertEqual({item.name for item in self.items}, EXPECTED_FILES)
        self.assertEqual(self.summary.total, len(EXPECTED_FILES))
        self.assertEqual(self.summary.analyzed, len(EXPECTED_FILES))
        self.assertEqual(self.summary.unsupported_or_failed, 0)
        for item in self.items:
            self.assertEqual(item.status, "analyzed", f"{item.name}: {item.error}")
            self.assertIsNotNone(item.result)

    def test_metadata_marker_scores_high(self) -> None:
        marker = self.by_name[MARKER_NAME]
        self.assertIsNotNone(marker.result)
        self.assertEqual(marker.result.band, RiskBand.HIGH)
        self.assertGreaterEqual(marker.result.score, 67)
        self.assertEqual(marker.result.source_guess.confidence, SourceConfidence.HIGH)
        self.assertIn("A1111", marker.result.source_guess.label)

    def test_marker_outranks_unmarked_images(self) -> None:
        marker_score = self.by_name[MARKER_NAME].result.score
        for name in EXPECTED_IMAGES - {MARKER_NAME}:
            score = self.by_name[name].result.score
            self.assertLess(score, marker_score, f"{name} scored {score}, expected below the metadata marker")

    def test_score_report_written(self) -> None:
        """Per-file scores recorded to JSON for trend inspection only."""
        destination = os.environ.get("DEEPFAKE_LENS_BENCH_REPORT")
        with tempfile.TemporaryDirectory() as tmp:
            out_path = Path(destination) if destination else Path(tmp) / "benchmark-report.json"
            report = _write_report(self.summary, self.items, out_path)
            loaded = json.loads(out_path.read_text(encoding="utf-8"))

        self.assertEqual(loaded, report)
        self.assertIn("NOT calibrated", loaded["note"])
        files = {entry["name"]: entry for entry in loaded["files"]}
        self.assertEqual(set(files), EXPECTED_FILES)
        self.assertEqual(files[MARKER_NAME]["band"], "high")


if __name__ == "__main__":
    unittest.main()

"""TB-7: the versioned generator / service string table — phase-0 values unchanged, sourced additions, neutral signer naming."""

from __future__ import annotations

import json
import unittest

from deepfake_lens.evidence_rules import GENERATOR_NAMES, generator_name_in
from deepfake_lens.generator_strings import SIGNER_TITLE, TABLE_PATH, c2pa_signer_evidence, tool_guess_rules
from deepfake_lens.image_metadata import guess_image_source
from deepfake_lens.result_types import EvidenceDirection, EvidenceStrength, SourceConfidence

PHASE0_LABELS = [
    "Midjourney/Niji 추정", "Flux / Black Forest Labs 추정", "Stable Diffusion 추정", "DALL-E/OpenAI 추정", "Google Imagen/Gemini 추정",
    "Adobe Firefly 추정", "Ideogram 추정", "Runway 추정", "Leonardo.ai 추정", "NovelAI 추정", "Recraft 추정", "Canva AI 추정", "Grok/xAI 추정",
]


class TableTest(unittest.TestCase):
    def test_phase0_rules_keep_their_order_and_names(self) -> None:
        self.assertEqual([label for label, _, _ in tool_guess_rules()][:13], PHASE0_LABELS)
        self.assertEqual(GENERATOR_NAMES, ("Flux", "Midjourney", "DALL-E", "DALL·E", "Imagen", "Stable Diffusion", "Firefly", "Gemini", "Nano Banana", "AI Generated", "Generated by AI"))

    def test_every_addition_and_signer_has_a_source(self) -> None:
        data = json.loads(TABLE_PATH.read_text(encoding="utf-8"))
        for rule in data["tool_guess_rules"][13:]:
            self.assertTrue(rule["source"] and rule["confidence"], rule["label"])
        for signer in data["c2pa_signers"]:
            self.assertTrue(signer["source"] and signer["confidence"], signer["match"])

    def test_additions_are_recognised(self) -> None:
        self.assertEqual(guess_image_source({"exif.Software": "AI generated;flux2"}).label, "Flux / Black Forest Labs 추정")
        self.assertEqual(guess_image_source({"exif.Software": "Dreamina"}).confidence, SourceConfidence.HIGH)
        self.assertEqual(guess_image_source({"exif.Software": "GIMP 2.10"}).confidence, SourceConfidence.UNKNOWN)
        self.assertEqual(generator_name_in("Adobe Firefly"), "Firefly")


class SignerTest(unittest.TestCase):
    def test_signer_is_named_neutrally(self) -> None:
        validation = {"present": True, "trusted": False, "signature": {"common_name": "OpenAI Media Service", "issuer": "OpenAI OpCo, LLC"},
                      "claim_generator": "OpenAI Media Service API"}
        [item] = c2pa_signer_evidence(validation)
        self.assertEqual(item.title, SIGNER_TITLE)
        self.assertEqual((item.direction, item.strength), (EvidenceDirection.NEUTRAL, EvidenceStrength.WEAK))
        self.assertIn("서명 신뢰가 확인되지 않은", item.detail)

    def test_unknown_signer_and_absent_manifest_add_nothing(self) -> None:
        self.assertEqual(c2pa_signer_evidence({"present": True, "signature": {"common_name": "Some Camera Co"}}), [])
        self.assertEqual(c2pa_signer_evidence({"present": False}), [])
        self.assertEqual(c2pa_signer_evidence(None), [])


if __name__ == "__main__":
    unittest.main()
